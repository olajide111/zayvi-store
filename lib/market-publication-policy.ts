/**
 * Zayvi market-specific publication policy.
 *
 * A score is never sufficient by itself: hard operational gates must also pass.
 * Each market is evaluated and published independently.
 */

export type PublicationMarket = string;
export type ProductRating = number;

export type MarketPublicationInputs = {
  productId: string;
  marketCode: PublicationMarket;
  rating: ProductRating; // 0–100, generated by the market assessment pipeline
  availability: "available" | "limited_stock" | "temporarily_unavailable" | "not_listed" | "restricted" | "verification_required";
  availabilityVerified: boolean;
  stockCheckedAt?: string;
  complianceStatus: "unknown" | "pending" | "approved" | "blocked";
  deliveryEstimateDays?: number;
  deliveryEstimateVerified: boolean;
  contribution: number;
  minimumContribution: number;
  evidenceCount: number;
  humanApprovalRequired?: boolean;
};

export type PublicationDecision = {
  productId: string;
  marketCode: PublicationMarket;
  rating: number;
  decision: "auto_publish" | "admin_review" | "hold" | "blocked";
  publishAllowed: boolean;
  reasons: string[];
  policyVersion: string;
};

export const DEFAULT_PUBLICATION_THRESHOLDS = {
  automaticPublishAt: 85,
  adminReviewAt: 65,
  policyVersion: "1.0.0",
} as const;

export function decideMarketPublication(
  input: MarketPublicationInputs,
): PublicationDecision {
  const reasons: string[] = [];

  if (!Number.isFinite(input.rating) || input.rating < 0 || input.rating > 100) {
    throw new Error("Product rating must be between 0 and 100.");
  }

  if (input.complianceStatus === "blocked" || input.availability === "restricted") {
    return {
      productId: input.productId,
      marketCode: input.marketCode,
      rating: input.rating,
      decision: "blocked",
      publishAllowed: false,
      reasons: ["Product is restricted or blocked for this market."],
      policyVersion: DEFAULT_PUBLICATION_THRESHOLDS.policyVersion,
    };
  }

  if (input.availability !== "available" && input.availability !== "limited_stock") {
    reasons.push("Product availability is not confirmed for this market.");
  }
  if (!input.availabilityVerified) reasons.push("Supplier availability has not been verified.");
  if (input.complianceStatus !== "approved") reasons.push("Market compliance approval is incomplete.");
  if (input.deliveryEstimateDays === undefined || !input.deliveryEstimateVerified) {
    reasons.push("A verified delivery estimate is required.");
  }
  if (input.contribution <= 0) reasons.push("Expected contribution is not positive.");
  if (input.contribution < input.minimumContribution) {
    reasons.push("Expected contribution is below the configured market minimum.");
  }
  if (input.evidenceCount < 2) reasons.push("At least two supporting evidence records are required.");

  if (reasons.length > 0) {
    return {
      productId: input.productId,
      marketCode: input.marketCode,
      rating: input.rating,
      decision: "hold",
      publishAllowed: false,
      reasons,
      policyVersion: DEFAULT_PUBLICATION_THRESHOLDS.policyVersion,
    };
  }

  if (input.humanApprovalRequired || input.rating < DEFAULT_PUBLICATION_THRESHOLDS.automaticPublishAt) {
    return {
      productId: input.productId,
      marketCode: input.marketCode,
      rating: input.rating,
      decision: "admin_review",
      publishAllowed: false,
      reasons: [
        input.humanApprovalRequired
          ? "This market or product requires explicit human approval."
          : "Rating is below the automatic publication threshold.",
      ],
      policyVersion: DEFAULT_PUBLICATION_THRESHOLDS.policyVersion,
    };
  }

  return {
    productId: input.productId,
    marketCode: input.marketCode,
    rating: input.rating,
    decision: "auto_publish",
    publishAllowed: true,
    reasons: [
      "Rating meets the automatic publication threshold.",
      "Market-specific availability, compliance, delivery, evidence and contribution gates passed.",
    ],
    policyVersion: DEFAULT_PUBLICATION_THRESHOLDS.policyVersion,
  };
}
